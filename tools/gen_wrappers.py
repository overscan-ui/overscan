GENERATED = "/* GENERATED by tools/gen_wrappers.py. Do not edit; re-run the script. */"


def emit_split(els, framework, runtime):
    """One module per component, and an index that only re-exports them.

    🔴 THE INDEX USED TO IMPORT THE WHOLE KIT. `import '../overscan.js'` sat at
    the top of index.js, so `import { OvRadar } from 'overscan/react'`
    registered every element in the kit, and in a Vite production build one
    component cost 143 kB gzip over React alone (tools/consumer-test.sh,
    2026-09-12). Each component now imports only its own element, the way the
    Svelte components always did, and package.json lists the files that DO have
    side effects, so a bundler drops every wrapper module nobody imports along
    with the element it would have loaded.

    ⚠️ DEV SERVERS DO NOT TREE-SHAKE. Vite dev pre-bundles the whole index, so
    every element still registers there. The cost is a production-build
    property, and the consumer check asserts it only in the build.
    """
    d = OUT / framework
    d.mkdir(exist_ok=True)
    (d / 'runtime.js').write_text(runtime)
    index, keep = [GENERATED], {'index.js', 'runtime.js'}
    for e in els:
        props = [m['name'] for m in e['members']]
        evs = '{' + ', '.join(f"{k}: '{v}'"
                                 for k, v in e['wrappers'][framework].items()) + '}'
        file = f'{iface(e)}.js'
        keep.add(file)
        (d / file).write_text('\n'.join([
            GENERATED,
            f"import '../{e['module'].replace('src/', '', 1)}';",
            "import { wrap } from './runtime.js';",
            '',
            f"export const {iface(e)} = wrap('{e['name']}', {json.dumps(props)}, {evs});",
        ]) + '\n')
        index.append(f"export {{ {iface(e)} }} from './{file}';")
    # A removed element must not leave a wrapper behind that imports nothing.
    for stale in sorted(p for p in d.glob('*.js') if p.name not in keep):
        stale.unlink()
    (d / 'index.js').write_text('\n'.join(index) + '\n')
    return len(els)


def emit_react(els):
    return emit_split(els, 'react', REACT_RUNTIME)


def emit_vue(els):
    return emit_split(els, 'vue', VUE_RUNTIME)


def emit_svelte(els):
    d = OUT / 'svelte'
    d.mkdir(exist_ok=True)
    for e in els:
        props = [m['name'] for m in e['members']]
        handlers = list(e['wrappers']['svelte'])
        decl = ''.join(f'{n} = undefined, ' for n in props + handlers)
        assigns = ''.join(
            f"    if (host && {n} !== undefined) host.{n} = {n};\n" for n in props)
        if not assigns:
            assigns = "    void host;\n"
        listeners = ''.join(
            f"      (() => {{ const h = (e) => {name}?.(e); "
            f"host.addEventListener('{ev}', h); "
            f"return () => host.removeEventListener('{ev}', h); }})(),\n"
            for name, ev in e['wrappers']['svelte'].items())
        (d / f"{iface(e)}.svelte").write_text(SVELTE_COMPONENT.format(
            tag=e['name'], module=e['module'].replace('src/', ''),
            first=(e['events'][0].split(':', 1)[1] if e['events'] else 'commit'),
            props=decl, assigns=assigns, listeners=listeners))
    index = ["/* GENERATED by tools/gen_wrappers.py. Do not edit; re-run the script. */"]
    for e in els:
        index.append(f"export {{ default as {iface(e)} }} "
                     f"from './{iface(e)}.svelte';")
    (d / 'index.js').write_text('\n'.join(index) + '\n')
    return len(els)


def selftest():
    """Refuses to report until it has seen the cases that matter."""
    fails = []
    els = load()
    tr = next((e for e in els if e['name'] == 'ov-transport'), None)
    if tr:
        w = tr['wrappers']
        if w['react'].get('onPlay') != 'ov:play':
            fails.append(f"react spelling wrong: {w['react']}")
        if w['vue'].get('play') != 'ov:play':
            fails.append(f"vue spelling wrong: {w['vue']}")
        if w['svelte'].get('onplay') != 'ov:play':
            fails.append(f"svelte spelling wrong: {w['svelte']}")

    # 40 since ov-countdown (2026-09-11).
    # 43 since ov-track (2026-09-11).
    # 48 since ov-downlink (2026-09-11).
    # 53 since ov-orbit (2026-09-11).
    # 81 since ov-geomap and ov-tactical.
    # 82 since ov-watchdog.
    # 83 since ov-authority.
    # 84 since ov-solid.
    # 85 since ov-datablock.
    if len(els) != 85:
        fails.append(f'expected 85 elements, manifest has {len(els)}')

    # 🔴 The reason wrappers exist. If an element with events came back with
    # none, the wrapper would be a silent pass-through and the colon problem
    # would be unsolved on that element.
    tr = next((e for e in els if e['name'] == 'ov-transport'), None)
    if not tr or 'ov:play' not in tr['events'] or 'ov:seek' not in tr['events']:
        fails.append('ov-transport lost its events; the wrapper would bind nothing')

    ch = next((e for e in els if e['name'] == 'ov-chart'), None)
    if not ch or [m['name'] for m in ch['members']] != ['values']:
        fails.append('ov-chart lost its values property; readings would go '
                     'through attributes and stringify')
    return fails


if __name__ == '__main__':
    f = selftest()
    if f:
        print('gen_wrappers.py SELFTEST FAILED:', *f, sep='\n  ')
        sys.exit(1)
    print('selftest ok')
    els = load()
    print(f'wrote src/react/  ({emit_react(els)} components)')
    print(f'wrote src/vue/    ({emit_vue(els)} components)')
    print(f'wrote src/svelte/ ({emit_svelte(els)} components)')
