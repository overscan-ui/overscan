mut('m-open-stall-seconds', "const closed = this._stallMs / 1000;", "const closed = (this._stallMs + (this._stallFrom === null ? 0 : now - this._stallFrom)) / 1000; /* MUTANT */")
# n: the icon version draws pause over any play asked for, moving or not.
mut('n-pause-icon-pending', "icon($.play, this._intent ? (pending ? 'pending' : 'pause') : 'play');", "icon($.play, this._intent ? 'pause' : 'play'); /* MUTANT */")
# h: a frozen picture under a running clock reads as playing.
mut('h-picture-frozen', "if (this._lastFrame !== null && now - this._lastFrame > freezeMs) return 'picture-frozen';", "/* MUTANT */")
