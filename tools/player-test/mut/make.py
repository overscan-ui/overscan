mut('j-cc-invented', "$.cc.hidden = !tracks.length;", "$.cc.hidden = false; /* MUTANT */")
# k: the hover readout calls an unbuffered point buffered.
mut('k-hover-buffered', "    return 'NOT BUFFERED';", "    return 'BUFFERED'; /* MUTANT */")
# l: a waveform is drawn with no scale to put it on (no duration, or a live stream).
mut('l-wave-no-scale', "this._wave.src === (m.currentSrc || m.src) && sc && !v.isLive;", "this._wave.src === (m.currentSrc || m.src); /* MUTANT */")
